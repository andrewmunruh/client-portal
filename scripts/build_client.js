#!/usr/bin/env node
// Build a static, client-only copy of the portal for ONE tenant.
//   node scripts/build_client.js [tenantId=colby] [--out DIR]
// Default output: c/<slug>/ where <slug> is a random id kept in scripts/clients.json (created on first build).
// The copy contains only that tenant's client-safe data and the client code (app.js + extras.js).
// admin.js (admin views, role switcher, tenant picker, demo mode, revenue tile) is NOT copied, and the
// prototype's ?role= / ?tenant= / ?demo= handling lives only in admin.js, so the copy ignores those params.
const fs=require('fs'),path=require('path'),vm=require('vm'),crypto=require('crypto');
const ROOT=path.resolve(__dirname,'..');
const args=process.argv.slice(2);const oi=args.indexOf('--out');
const outArg=oi>=0?args[oi+1]:null;const tid=(args.filter((a,i)=>!a.startsWith('--')&&i!==oi+1)[0])||'colby';

// Load data.js in a sandbox (no DOM needed).
const ctx={};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT,'data.js'),'utf8')+'\n;this.__out={TENANTS,LATER,STEPS};',ctx);
const {TENANTS,LATER,STEPS}=ctx.__out;
const t=TENANTS.find(x=>x.id===tid);if(!t){console.error(`No tenant "${tid}"`);process.exit(1);}

// Whitelist of client-safe fields. Admin-only data (rules, jobValue/revenue, integrations, hours/windows, status) is dropped.
const KEEP=['id','name','owner','their','loc','fake','demo','paused','workflow','approvals','questions','confirms','flags','log','leads','baseline','pilot','steps','finishedJobs','openQuotes','doneInvoices'];
const safe=Object.fromEntries(KEEP.filter(k=>k in t).map(k=>[k,t[k]]));
safe.settings={delay:t.settings.delay,greeting:t.settings.greeting};
safe.requests=[];safe.feedback=[];

// Output folder
const cfgPath=path.join(__dirname,'clients.json');const cfg=fs.existsSync(cfgPath)?JSON.parse(fs.readFileSync(cfgPath,'utf8')):{};
if(!outArg&&!cfg[tid]){cfg[tid]={slug:crypto.randomBytes(8).toString('hex')};fs.writeFileSync(cfgPath,JSON.stringify(cfg,null,2)+'\n');}
const out=path.resolve(outArg||path.join(ROOT,'c',cfg[tid].slug));fs.mkdirSync(out,{recursive:true});

const J=v=>JSON.stringify(v);
// Client code is copied with whole-line comments removed (they describe the prototype's admin side).
const src=f=>fs.readFileSync(path.join(ROOT,f),'utf8').split('\n').filter(l=>!/^\s*\/\//.test(l)).join('\n');
const files={
 'data.js':`// GENERATED by scripts/build_client.js. Do not edit. Client-only copy for one tenant; ALL records are EXAMPLE DATA.\nconst LATER=${J(LATER)};\nconst STEPS=${J(STEPS)};\nconst TENANTS=[${J(safe)}];\n`,
 'app.js':src('app.js'),
 'extras.js':src('extras.js'),
 'styles.css':fs.readFileSync(path.join(ROOT,'styles.css'),'utf8'),
 'index.html':`<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow">
<title>${t.name.replace(/[<&]/g,'')} — bot portal (preview)</title>
<link rel="stylesheet" href="styles.css"></head>
<body>
<div class="proto"><span class="full">Preview · all numbers and records are <b>example data</b> · changes reset on reload</span><span class="short">Preview · <b>example data</b> · resets on reload</span></div>
<header class="top">
  <div class="brand"><span class="dot"></span><div><b>Back-office bots</b><small>run by Andy Unruh</small></div></div>
</header>
<div class="shell">
  <nav id="nav"></nav>
  <main id="main"></main>
</div>
<div id="modal" class="modal hidden"><div class="mbox" id="mbox" role="dialog" aria-modal="true"></div></div>
<div id="toast" class="toast hidden" role="status"></div>
<script src="data.js"></script>
<script src="app.js"></script>
<script src="extras.js"></script>
<script>render()</script>
</body></html>
`};
for(const [n,c] of Object.entries(files))fs.writeFileSync(path.join(out,n),c);

// Self-check: fail the build if anything admin-only or another tenant leaked into the copy.
const all=Object.values(files).join('\n');
const others=TENANTS.filter(x=>x.id!==tid).flatMap(x=>[x.name,x.id,x.owner]);
const banned=['ADMIN_NAV','adminHead','admin.js','Andy admin','role=admin','tenantSel','roleSeg','demoBtn','jobValue','revenue','baselineAdmin','onboardAdmin'];
const leaks=[...others.filter(w=>new RegExp(`\\b${w.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}\\b`).test(all)).map(w=>'other tenant: '+w),...banned.filter(w=>all.includes(w)).map(w=>'admin token: '+w)];
if(leaks.length){console.error('LEAK in client copy:\n  '+leaks.join('\n  '));process.exit(2);}
console.log(`Built client copy for ${t.name} → ${path.relative(ROOT,out)||out}`);
